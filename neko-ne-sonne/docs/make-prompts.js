function cellSvg(m, x, y) {
  const s = 512, band = s * 0.06, pw = s * 0.22, c = s / 2;
  let g = `<g transform="translate(${x},${y})">`;
  g += `<rect width="${s}" height="${s}" fill="#e8dcc4"/>`;
  g += `<rect x="${band}" y="${band}" width="${s - band * 2}" height="${s - band * 2}" fill="#cfe3b5"/>`;
  const seg = { 1: [c - pw / 2, 0, pw, c + pw / 2], 2: [c - pw / 2, c - pw / 2, s - c + pw / 2, pw], 4: [c - pw / 2, c - pw / 2, pw, s - c + pw / 2], 8: [0, c - pw / 2, c + pw / 2, pw] };
  const wall = { 1: [band, band, s - band * 2, 18], 2: [s - band - 18, band, 18, s - band * 2], 4: [band, s - band - 18, s - band * 2, 18], 8: [band, band, 18, s - band * 2] };
  if (m) g += `<rect x="${c - pw / 2}" y="${c - pw / 2}" width="${pw}" height="${pw}" fill="#c9a878"/>`;
  [1, 2, 4, 8].forEach((d) => {
    if (m & d) { const r = seg[d]; g += `<rect x="${r[0]}" y="${r[1]}" width="${r[2]}" height="${r[3]}" fill="#c9a878"/>`; }

  });
  return g + '</g>';
}
function sheetSvg(masks) {
  let body = '';
  masks.forEach((m, i) => { body += cellSvg(m, (i % 3) * 512, Math.floor(i / 3) * 512); });
  // マスの さかいめ（見本なので 細い 線で 区切る）
  for (let k = 1; k < 3; k++) body += `<line x1="${k * 512}" y1="0" x2="${k * 512}" y2="1536" stroke="#ffffff" stroke-width="4"/><line x1="0" y1="${k * 512}" x2="1536" y2="${k * 512}" stroke="#ffffff" stroke-width="4"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1536" height="1536" viewBox="0 0 1536 1536">${body}</svg>`;
}

(async () => {
  const b = await chromium.launch();
  const pg = await b.newPage({ viewport: { width: 1536, height: 1536 } });
  const sheets = SHAPES.map((s) => [s.key, Array(9).fill(s.m)]);
  sheets.push(['facility', [7, 3, 1, 7, 3, 1, 7, 3, 1]]);
  for (const [k, masks] of sheets) {
    await pg.setContent(`<html><body style="margin:0">${sheetSvg(masks)}</body></html>`);
    await pg.screenshot({ path: path.join(GUIDES, `guide-${k}.png`), clip: { x: 0, y: 0, width: 1536, height: 1536 } });
  }
  await b.close();
  console.log('done');
})();
