function sides(m) {
  const open = [N, E, S, W].filter((d) => m & d).map((d) => SIDE[d]);
  const closed = [N, E, S, W].filter((d) => !(m & d)).map((d) => SIDE[d]);
  return { open, closed };
}
function edgeRule(m) {
  const { open, closed } = sides(m);
  const a = open.length ? `・猫道が抜ける辺：${open.join('・')}（その辺のちょうど真ん中）` : '・猫道が抜ける辺：なし（このマスには猫道を描かない。街区の建物や庭だけ）';
  const b = closed.length ? `・猫道が来ない辺：${closed.join('・')}（塀でふさがず、建物や庭がそのまま歩道まで続く）` : '・猫道が来ない辺：なし';
  return `${a}\n${b}`;
}

